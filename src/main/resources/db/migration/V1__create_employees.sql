CREATE TABLE employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id VARCHAR(20) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    department VARCHAR(60) NOT NULL,
    designation VARCHAR(80) NOT NULL,
    date_of_joining DATE NOT NULL,
    salary NUMERIC(12, 2) NOT NULL CHECK (salary >= 0),
    status VARCHAR(10) NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT uk_employee_id UNIQUE (employee_id),
    CONSTRAINT uk_employee_email UNIQUE (email)
);

CREATE UNIQUE INDEX uk_employee_id_case ON employees (UPPER(employee_id));
CREATE UNIQUE INDEX uk_employee_email_case ON employees (LOWER(email));
CREATE INDEX idx_employee_department_status ON employees (department, status);
